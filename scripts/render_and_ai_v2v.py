#!/usr/bin/env python3
"""
SEKIYADO SOARING：フライト録画 JSON → Blender で動画レンダリング → 動画生成 AI で質感を実写風に補正 → 連結・比較動画

  1. Blender（4.2 LTS 推奨）で scripts/blender_import_flight.py を実行し、Beauty・Mist（深度）・Normal の PNG 連番を作る
  2. PNG 連番を beauty.mp4 / mist.mp4 / normal.mp4 にまとめる（ffmpeg）
  3. AI に渡しやすい長さ（49 コマ ＝ 8 fps で約 6 秒）に区切る
  4. --backend diffusers：CogVideoX の Video-to-Video で各区間を変換し、つなぎ直す（NVIDIA GPU・VRAM 16 GB 程度が目安）
     --backend dry-run ：区間ごとの動画とプロンプト表だけを作る（Runway などのサービスへ手で入れる用）
  5. final_ai.mp4（AI 補正版）と compare_before_after.mp4（左：Blender、右：AI）を作る

地形・建物の位置は国土地理院のデータどおりだが、AI が描いた細部（草の様子、建物の窓など）は実物と違うことがある。
完成動画の隅には「AI 補正」の表示を入れる（--no-label で外せるが、公開するときは表示を残すことを勧める）。

使い方の例：
  python scripts/render_and_ai_v2v.py --blender /path/to/blender \\
    --data-dir ./assets/data --flight ./sekiyado_clip30s_20261125_150000.json \\
    --out ./renders/run01 --duration-sec 28 --backend dry-run

  # 既にレンダリング済みなら Blender を飛ばして AI 変換だけ
  python scripts/render_and_ai_v2v.py --skip-blender --out ./renders/run01 --backend diffusers --strength 0.5
"""

import argparse
import os
import math
import shutil
import subprocess
import sys
from pathlib import Path

AI_FPS = 8          # CogVideoX の学習時のフレームレート
AI_FRAMES = 49      # CogVideoX が一度に扱うコマ数（約 6.1 秒）
AI_W, AI_H = 720, 480

DEFAULT_PROMPT = (
    "Realistic aerial footage from a glider flying low over the flat farmland and riverside of the Kanto plain in Japan, "
    "rice paddies, grass fields, levees, small houses, natural afternoon sunlight, shot on a cinema camera, sharp detail"
)
DEFAULT_NEGATIVE = "cartoon, painting, CGI look, low quality, blurry, distorted, warped geometry, text, watermark, flicker"
LABEL = "AI-enhanced - terrain and layout from GSI data, surface details generated by AI"


def run(cmd, desc):
    print(f"[PIPE] {desc}")
    res = subprocess.run([str(c) for c in cmd])
    if res.returncode != 0:
        raise SystemExit(f"[PIPE] 失敗：{desc}（終了コード {res.returncode}）")


def need(tool):
    if not shutil.which(tool):
        raise SystemExit(f"{tool} が見つかりません。インストールして PATH を通してください。")


def probe_frames(video):
    out = subprocess.check_output(["ffprobe", "-v", "error", "-select_streams", "v:0", "-count_frames",
                                   "-show_entries", "stream=nb_read_frames", "-of", "csv=p=0", str(video)], text=True)
    return int(out.strip().split(",")[0])


def render_with_blender(args, out):
    script = Path(__file__).resolve().parent / "blender_import_flight.py"
    cmd = [args.blender, "--background", "--python", script, "--",
           "--data-dir", args.data_dir, "--flight", args.flight, "--out", out,
           "--fps", args.fps, "--start-sec", args.start_sec, "--duration-sec", args.duration_sec,
           "--shutter", args.shutter, "--grass-density", args.grass_density,
           "--engine", args.engine, "--samples", args.samples, "--width", args.width, "--height", args.height,
           "--render"]
    if args.skip_far:
        cmd.append("--skip-far")
    run(cmd, "Blender でレンダリング")


def encode_sequences(out, fps):
    """Blender のコンポジターが書き出した PNG 連番（beauty/ mist/ normal/）を MP4 にする"""
    made = {}
    for name in ("beauty", "mist", "normal"):
        seq = sorted((out / name).glob("*.png"))
        if not seq:
            continue
        # 版によってファイル名の付き方が違うので、frame_0001.png … に揃えてから読む
        if [p.name for p in seq] != [f"frame_{i:04d}.png" for i in range(1, len(seq) + 1)]:
            tmp = [p.rename(p.with_name(f"__tmp_{i:05d}.png")) for i, p in enumerate(seq, 1)]
            for i, p in enumerate(tmp, 1):
                p.rename(p.with_name(f"frame_{i:04d}.png"))
        dst = out / f"{name}.mp4"
        run(["ffmpeg", "-y", "-loglevel", "error", "-framerate", fps, "-start_number", 1,
             "-i", out / name / "frame_%04d.png", "-c:v", "libx264", "-crf", "16", "-pix_fmt", "yuv420p", dst],
            f"{name} の連番 → {dst.name}")
        made[name] = dst
    if "beauty" not in made:
        raise SystemExit(f"{out}/beauty/ に PNG がありません。Blender のログに「PNG の分割出力を設定できませんでした」が出ていないか確認してください。")
    return made


def find_blender(given):
    """Blender の実行ファイルを探す。指定がなければ PATH、Windows の標準の場所、macOS のアプリの順"""
    if given and given != "blender":
        return given
    if shutil.which("blender"):
        return "blender"
    cands = sorted(Path(os.environ.get("ProgramFiles", r"C:\Program Files"), "Blender Foundation").glob("Blender */blender.exe"),
                   key=lambda p: [int(x) for x in p.parent.name.split()[-1].split(".") if x.isdigit()], reverse=True)
    cands.append(Path("/Applications/Blender.app/Contents/MacOS/Blender"))
    for c in cands:
        if c.exists():
            print(f"[PIPE] Blender：{c}")
            return str(c)
    raise SystemExit("Blender が見つかりません。--blender で実行ファイルを指定してください。")


def ai_input_filter():
    # 16:9 などの映像を、伸ばさず中央を 3:2（720×480）に切り出す
    return f"fps={AI_FPS},scale={AI_W}:{AI_H}:force_original_aspect_ratio=increase,crop={AI_W}:{AI_H}"


def split_for_ai(beauty, chunks_dir):
    """8 fps・720×480 に整えて 49 コマずつに区切る。
    最後の区間は手前へずらして 49 コマ分を取り（前の区間と重なる）、重なった先頭 skip コマは変換後に捨てる。
    動画全体が 49 コマ未満のときだけ、最後のコマを繰り返して長さをそろえる"""
    chunks_dir.mkdir(parents=True, exist_ok=True)
    prep = chunks_dir / "prep_8fps.mp4"
    run(["ffmpeg", "-y", "-loglevel", "error", "-i", beauty, "-vf", ai_input_filter(),
         "-c:v", "libx264", "-crf", "14", "-pix_fmt", "yuv420p", prep], "AI 用に 8 fps・720×480 へ整形")
    total = probe_frames(prep)
    n = max(1, math.ceil(total / AI_FRAMES))
    chunks = []
    for i in range(n):
        nominal = i * AI_FRAMES
        real = min(AI_FRAMES, total - nominal)
        first = max(0, min(nominal, total - AI_FRAMES))
        skip = nominal - first
        last = min(total, first + AI_FRAMES) - 1
        dst = chunks_dir / f"chunk_{i:03d}.mp4"
        vf = f"select='between(n\\,{first}\\,{last})',setpts=N/({AI_FPS}*TB)"
        if last - first + 1 < AI_FRAMES:
            vf += f",tpad=stop_mode=clone:stop={AI_FRAMES - (last - first + 1)}"
        run(["ffmpeg", "-y", "-loglevel", "error", "-i", prep, "-vf", vf, "-r", AI_FPS, "-frames:v", AI_FRAMES,
             "-c:v", "libx264", "-crf", "14", "-pix_fmt", "yuv420p", dst],
            f"区間 {i + 1}/{n}（使うのは {skip + 1}〜{skip + real} コマ目）")
        chunks.append((dst, real, skip))
    return chunks


def v2v_diffusers(chunks, ai_dir, args):
    import torch
    from diffusers import CogVideoXDPMScheduler, CogVideoXVideoToVideoPipeline
    from diffusers.utils import export_to_video, load_video

    ai_dir.mkdir(parents=True, exist_ok=True)
    dtype = torch.bfloat16 if torch.cuda.is_available() and torch.cuda.is_bf16_supported() else torch.float16
    pipe = CogVideoXVideoToVideoPipeline.from_pretrained(args.model_id, torch_dtype=dtype)
    pipe.scheduler = CogVideoXDPMScheduler.from_config(pipe.scheduler.config, timestep_spacing="trailing")
    pipe.enable_model_cpu_offload()
    pipe.vae.enable_slicing()
    pipe.vae.enable_tiling()

    outs = []
    for i, (src, real, skip) in enumerate(chunks):
        # 区間ごとに模様が変わりにくいよう、乱数の種は全区間で同じにする
        gen = torch.Generator(device="cpu").manual_seed(args.seed)
        print(f"[AI] 区間 {i + 1}/{len(chunks)} を変換中（strength={args.strength}）")
        frames = pipe(video=load_video(str(src)), prompt=args.prompt, negative_prompt=args.negative_prompt,
                      strength=args.strength, guidance_scale=args.guidance_scale,
                      num_inference_steps=args.steps, use_dynamic_cfg=True, generator=gen).frames[0]
        raw = ai_dir / f"ai_raw_{i:03d}.mp4"
        export_to_video(frames[skip:skip + real], str(raw), fps=AI_FPS)  # 前の区間と重なる分・水増し分は捨てる
        outs.append(raw)
    return outs


def to_output_fps(src, dst, fps, interp, real):
    """8 fps の AI 出力を出力のフレームレートへ。mci は動き補間（滑らかだが遅い）、dup はコマの複製。
    区間をつないだときに元の動画とずれないよう、コマ数を元の長さ（real / 8 秒）ちょうどにそろえる"""
    n = max(1, round(real * fps / AI_FPS))
    mci = interp == "mci" and real >= 8  # ごく短い区間は動き補間できないので複製にする
    vf = f"minterpolate=fps={fps}:mi_mode=mci:mc_mode=aobmc:vsbmc=1" if mci else f"fps={fps}"
    run(["ffmpeg", "-y", "-loglevel", "error", "-i", src, "-vf",
         f"{vf},tpad=stop_mode=clone:stop={fps},scale=1080:720:flags=lanczos", "-frames:v", n,
         "-c:v", "libx264", "-crf", "16", "-pix_fmt", "yuv420p", dst], f"{Path(src).name} → {fps} fps（{n} コマ）")


def add_label(src, dst):  # LABEL にはコロンや引用符を入れない（drawtext の区切り文字になる）
    """完成動画の右下に AI 補正の表示を入れる。フォントが見つからない環境では表示なしでコピーし、警告する"""
    vf = (f"drawtext=text='{LABEL}':fontsize=18:fontcolor=white@0.85:box=1:boxcolor=black@0.35:boxborderw=6:"
          "x=w-tw-16:y=h-th-16")
    res = subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(src), "-vf", vf,
                          "-c:v", "libx264", "-crf", "16", "-pix_fmt", "yuv420p", str(dst)])
    if res.returncode != 0:
        print("[PIPE] 警告：AI 補正の表示を入れられませんでした（ffmpeg の drawtext が使えない）。公開時は説明文で明記してください。")
        shutil.copy(src, dst)


def stitch(parts, chunks, out, fps, interp, label):
    smooth = []
    for p, (_, real, _skip) in zip(parts, chunks):
        q = p.with_name(p.stem.replace("ai_raw", "ai_out") + ".mp4")
        to_output_fps(p, q, fps, interp, real)
        smooth.append(q)
    lst = out / "concat_list.txt"
    lst.write_text("".join(f"file '{p.resolve().as_posix()}'\n" for p in smooth), encoding="utf-8")
    joined = out / "ai_joined.mp4"
    run(["ffmpeg", "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", lst, "-c", "copy", joined], "区間をつなぐ")
    final = out / "final_ai.mp4"
    if label:
        add_label(joined, final)
    else:
        shutil.copy(joined, final)

    # 比較動画：左に Blender（AI と同じ 3:2 の切り出し）、右に AI
    compare = out / "compare_before_after.mp4"
    run(["ffmpeg", "-y", "-loglevel", "error", "-i", out / "beauty.mp4", "-i", final, "-filter_complex",
         f"[0:v]fps={fps},scale={AI_W}:{AI_H}:force_original_aspect_ratio=increase,crop={AI_W}:{AI_H}[l];"
         f"[1:v]scale={AI_W}:{AI_H}[r];[l][r]hstack=inputs=2[v]",
         "-map", "[v]", "-shortest", "-c:v", "libx264", "-crf", "18", "-pix_fmt", "yuv420p", compare], "比較動画")
    return final, compare


def write_sheet(out, chunks, args):
    lines = ["# AI 変換用の区間とプロンプト", "",
             f"各区間は 8 fps・720×480・{AI_FRAMES} コマです。Runway などの Video-to-Video に手で入れる場合に使ってください。",
             "最後の区間は前の区間と重なっています。つなぐときは表の「使うコマ」だけを使ってください。", "",
             "| 区間 | ファイル | 使うコマ |", "| --- | --- | --- |"]
    lines += [f"| {i + 1} | {p.name} | {skip + 1}〜{skip + real} |" for i, (p, real, skip) in enumerate(chunks)]
    lines += ["", "## プロンプト", "", args.prompt, "", "## ネガティブプロンプト", "", args.negative_prompt, "",
              "## 注意", "", "AI が描いた細部は実物と異なることがあります。公開するときは「AI 補正あり」と明記してください。"]
    (out / "ai_prompt_sheet.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description="フライト録画 → Blender → AI 実写風動画")
    ap.add_argument("--out", required=True, help="出力フォルダー")
    ap.add_argument("--data-dir", default="./assets/data")
    ap.add_argument("--flight", help="シミュレーターで保存したフライト JSON（--skip-blender のときは不要）")
    ap.add_argument("--blender", default="blender", help="Blender の実行ファイル")
    ap.add_argument("--skip-blender", action="store_true", help="既にある PNG 連番／beauty.mp4 を使う")
    ap.add_argument("--fps", type=int, default=24)
    ap.add_argument("--start-sec", type=float, default=0.0)
    ap.add_argument("--duration-sec", type=float, default=28.0)
    ap.add_argument("--shutter", type=float, default=0.45)
    ap.add_argument("--grass-density", type=float, default=6.0)
    ap.add_argument("--engine", default="CYCLES", choices=["CYCLES", "EEVEE"])
    ap.add_argument("--samples", type=int, default=32)
    ap.add_argument("--width", type=int, default=1280)
    ap.add_argument("--height", type=int, default=720)
    ap.add_argument("--skip-far", action="store_true")
    ap.add_argument("--backend", default="dry-run", choices=["dry-run", "diffusers"])
    ap.add_argument("--model-id", default="THUDM/CogVideoX-5b")
    ap.add_argument("--prompt", default=DEFAULT_PROMPT)
    ap.add_argument("--negative-prompt", default=DEFAULT_NEGATIVE)
    ap.add_argument("--strength", type=float, default=0.5, help="AI の書き換えの強さ（小さいほど Blender の形に忠実）")
    ap.add_argument("--guidance-scale", type=float, default=6.0)
    ap.add_argument("--steps", type=int, default=50)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--interp", default="mci", choices=["mci", "dup"], help="8 fps → 出力 fps の補間方法")
    ap.add_argument("--no-label", action="store_true", help="AI 補正の表示を入れない")
    args = ap.parse_args()

    need("ffmpeg")
    need("ffprobe")
    out = Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    if not args.skip_blender:
        if not args.flight:
            raise SystemExit("--flight を指定してください")
        args.blender = find_blender(args.blender)
        render_with_blender(args, out)
    if args.skip_blender and (out / "beauty.mp4").exists() and not (out / "beauty").exists():
        beauty = out / "beauty.mp4"
    else:
        beauty = encode_sequences(out, args.fps)["beauty"]

    chunks = split_for_ai(beauty, out / "ai_chunks")
    write_sheet(out, chunks, args)
    if args.backend == "dry-run":
        print(f"[PIPE] 完了（dry-run）：{out / 'ai_chunks'} と ai_prompt_sheet.md を AI サービスへ")
        return
    parts = v2v_diffusers(chunks, out / "ai_out", args)
    final, compare = stitch(parts, chunks, out, args.fps, args.interp, not args.no_label)
    print(f"[PIPE] 完了：{final}\n[PIPE] 比較：{compare}")


if __name__ == "__main__":
    sys.exit(main())
